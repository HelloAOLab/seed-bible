/**
 * Generates the Android app's icons and splash screen from the Seed Bible
 * icon's shape (`packages/seed-bible/seed-bible/components/seedBibleIconShape.ts`).
 *
 * Run from `mobile/` after changing the icon or its intro animation:
 *
 *   pnpm assets:android
 *
 * Writes, under `android/app/src/main/res/`:
 * - `drawable/ic_launcher_foreground.xml`: the adaptive launcher icon's
 *   foreground (Android 8+), also used as its themed/monochrome layer.
 * - `drawable/splash_icon_animated.xml`: the splash screen icon. Android 12+
 *   plays the same seed → trunk → pages intro as the web app's toolbar icon;
 *   earlier versions show it finished.
 * - `mipmap-<density>/ic_launcher.png` and `ic_launcher_round.png`: launcher
 *   icons for Android 7, which predates adaptive icons.
 *
 * and `assets/play-store-icon.png`, the 512 × 512 icon Google Play asks for.
 *
 * The PNGs are rendered with Puppeteer's Chrome (see `iconRendering.ts`).
 */
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import {
  SEED_BIBLE_ICON_BRANCHES,
  SEED_BIBLE_ICON_HEIGHT,
  SEED_BIBLE_ICON_PAGE_SIDES,
  SEED_BIBLE_ICON_PATH,
  SEED_BIBLE_ICON_SEED,
  SEED_BIBLE_ICON_TRUNK,
} from "../../packages/seed-bible/seed-bible/components/seedBibleIconShape";
import {
  ICON_COLOR,
  iconSvg,
  MOBILE_DIR,
  placeIcon,
  renderPngs,
  round,
} from "./iconRendering";

const RES_DIR = path.join(MOBILE_DIR, "android/app/src/main/res");

const GENERATED_NOTICE =
  "<!-- Generated by mobile/scripts/generateAndroidAssets.ts. Don't edit by hand; run `pnpm assets:android` in mobile/. -->";

// Timings of the web intro, from `components/icons.css`; keep them in step.
const INTRO_MS = 900;
const SEED_MS = { start: 0, end: 180 };
const TRUNK_MS = { start: 120, end: 420 };
const PAGE_MS = 420;
/** The page reaches full width at 70% of its animation in the CSS. */
const PAGE_OPEN_FRACTION = 0.7;

const fraction = (ms: number) => round(Math.min(1, ms / INTRO_MS));

function iconGroupAttributes(viewport: number, iconWidth: number): string {
  const { scale, translateX, translateY } = placeIcon(iconWidth, viewport);
  return `android:scaleX="${scale}" android:scaleY="${scale}" android:translateX="${translateX}" android:translateY="${translateY}"`;
}

function staticIconVector(options: {
  sizeDp: number;
  viewport: number;
  iconWidth: number;
  fillColor: string;
}): string {
  return `<?xml version="1.0" encoding="utf-8"?>
${GENERATED_NOTICE}
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${options.sizeDp}dp"
    android:height="${options.sizeDp}dp"
    android:viewportWidth="${options.viewport}"
    android:viewportHeight="${options.viewport}">
    <group ${iconGroupAttributes(options.viewport, options.iconWidth)}>
        <path
            android:fillColor="${options.fillColor}"
            android:pathData="${SEED_BIBLE_ICON_PATH}" />
    </group>
</vector>
`;
}

// Adaptive icons are 108dp, of which launchers show at least the middle
// 72dp, and any shape they mask with keeps a 66dp circle. The icon is wide,
// so it's sized to keep its corners inside that circle.
const LAUNCHER_FOREGROUND = {
  sizeDp: 108,
  viewport: 108,
  iconWidth: 58,
  fillColor: ICON_COLOR,
};

// Android 12+ splash icons are 240dp and masked to a 160dp circle.
const SPLASH = {
  sizeDp: 240,
  viewport: 240,
  iconWidth: 130,
  fillColor: "@color/sb_icon",
};

const rectPath = (x: number, width: number, top: number, bottom: number) =>
  `M${x},${top} L${round(x + width)},${top} L${round(x + width)},${bottom} L${x},${bottom} Z`;

const polygonPath = (points: string) =>
  `M${points.trim().split(/\s+/).join(" L")} Z`;

const ellipsePath = ({ cx, cy, rx, ry }: typeof SEED_BIBLE_ICON_SEED) =>
  `M${round(cx - rx)},${cy} A${rx},${ry} 0 1,0 ${round(cx + rx)},${cy} A${rx},${ry} 0 1,0 ${round(cx - rx)},${cy} Z`;

interface Keyframe {
  at: number;
  value: number | string;
  interpolator?: string;
}

function propertyAnimator(
  property: string,
  keyframes: Keyframe[],
  valueType: "floatType" | "pathType" = "floatType"
): string {
  const frames = keyframes
    .map(
      (frame) =>
        `                    <keyframe android:fraction="${frame.at}" android:value="${frame.value}"${
          frame.interpolator
            ? ` android:interpolator="${frame.interpolator}"`
            : ""
        } />`
    )
    .join("\n");
  return `                <propertyValuesHolder android:propertyName="${property}" android:valueType="${valueType}">
${frames}
                </propertyValuesHolder>`;
}

function target(name: string, animators: string[]): string {
  return `    <target android:name="${name}">
        <aapt:attr name="android:animation">
            <objectAnimator android:duration="${INTRO_MS}">
${animators.join("\n")}
            </objectAnimator>
        </aapt:attr>
    </target>`;
}

const DECELERATE = "@android:interpolator/decelerate_cubic";
const OVERSHOOT = "@android:interpolator/overshoot";

/**
 * The splash icon for Android 12+, replaying the web intro: the seed pops in,
 * the trunk grows up out of it, then each branch opens out from the trunk
 * like a page.
 *
 * Every element's resting value in the vector is its *finished* state, and
 * each animation holds the hidden value until its moment comes using
 * keyframes rather than a start delay. That way older Android versions, which
 * draw this drawable without animating it, show the finished icon, and Android
 * 12+ never flashes the finished piece during a start delay.
 *
 * SVG's page bend (a skew on each page's outer half) has no VectorDrawable
 * equivalent, so here each page opens with a slight overshoot instead.
 */
function animatedSplashIcon(): string {
  const { viewport, sizeDp, iconWidth, fillColor } = SPLASH;
  const trunkHidden = rectPath(
    SEED_BIBLE_ICON_TRUNK.x,
    SEED_BIBLE_ICON_TRUNK.width,
    SEED_BIBLE_ICON_HEIGHT,
    SEED_BIBLE_ICON_HEIGHT
  );
  const trunkShown = rectPath(
    SEED_BIBLE_ICON_TRUNK.x,
    SEED_BIBLE_ICON_TRUNK.width,
    0,
    SEED_BIBLE_ICON_HEIGHT
  );

  const pages = SEED_BIBLE_ICON_BRANCHES.map((branch) => {
    const side = SEED_BIBLE_ICON_PAGE_SIDES[branch.side];
    return `            <group
                android:name="page_${branch.id}"
                android:pivotX="${side.hinge}"
                android:pivotY="${branch.hingeY}">
                <clip-path android:pathData="${polygonPath(branch.points)}" />
                <path
                    android:name="page_${branch.id}_fill"
                    android:fillColor="${fillColor}"
                    android:pathData="${SEED_BIBLE_ICON_PATH}" />
            </group>`;
  }).join("\n");

  const pageTargets = SEED_BIBLE_ICON_BRANCHES.flatMap((branch) => {
    const start = branch.delay * 1000;
    return [
      target(`page_${branch.id}`, [
        propertyAnimator("scaleX", [
          { at: 0, value: 0 },
          { at: fraction(start), value: 0 },
          {
            at: fraction(start + PAGE_MS * PAGE_OPEN_FRACTION),
            value: 1.04,
            interpolator: DECELERATE,
          },
          { at: fraction(start + PAGE_MS), value: 1 },
          { at: 1, value: 1 },
        ]),
      ]),
      target(`page_${branch.id}_fill`, [
        propertyAnimator("fillAlpha", [
          { at: 0, value: 0 },
          { at: fraction(start), value: 0 },
          { at: fraction(start + PAGE_MS * 0.1), value: 1 },
          { at: 1, value: 1 },
        ]),
      ]),
    ];
  });

  return `<?xml version="1.0" encoding="utf-8"?>
${GENERATED_NOTICE}
<animated-vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt">
    <aapt:attr name="android:drawable">
        <vector
            android:width="${sizeDp}dp"
            android:height="${sizeDp}dp"
            android:viewportWidth="${viewport}"
            android:viewportHeight="${viewport}">
            <group ${iconGroupAttributes(viewport, iconWidth)}>
            <group
                android:name="seed"
                android:pivotX="${SEED_BIBLE_ICON_SEED.cx}"
                android:pivotY="${SEED_BIBLE_ICON_SEED.cy}">
                <path
                    android:fillColor="${fillColor}"
                    android:pathData="${ellipsePath(SEED_BIBLE_ICON_SEED)}" />
            </group>
${pages}
            <!-- Above the pages, so their hinge ends tuck behind the trunk. -->
            <group>
                <clip-path android:name="trunk_reveal" android:pathData="${trunkShown}" />
                <path android:fillColor="${fillColor}" android:pathData="${SEED_BIBLE_ICON_PATH}" />
            </group>
            <!-- The pieces above leave hairline seams where their clips meet,
                 so the whole icon is swapped in once they've finished. -->
            <path
                android:name="whole"
                android:fillColor="${fillColor}"
                android:pathData="${SEED_BIBLE_ICON_PATH}" />
            </group>
        </vector>
    </aapt:attr>
${target("seed", [
  propertyAnimator("scaleX", [
    { at: 0, value: 0 },
    { at: fraction(SEED_MS.end), value: 1, interpolator: OVERSHOOT },
    { at: 1, value: 1 },
  ]),
  propertyAnimator("scaleY", [
    { at: 0, value: 0 },
    { at: fraction(SEED_MS.end), value: 1, interpolator: OVERSHOOT },
    { at: 1, value: 1 },
  ]),
])}
${target("trunk_reveal", [
  propertyAnimator(
    "pathData",
    [
      { at: 0, value: trunkHidden },
      { at: fraction(TRUNK_MS.start), value: trunkHidden },
      {
        at: fraction(TRUNK_MS.end),
        value: trunkShown,
        interpolator: DECELERATE,
      },
      { at: 1, value: trunkShown },
    ],
    "pathType"
  ),
])}
${pageTargets.join("\n")}
${target("whole", [
  propertyAnimator("fillAlpha", [
    { at: 0, value: 0 },
    { at: 0.999, value: 0 },
    { at: 1, value: 1 },
  ]),
])}
</animated-vector>
`;
}

/** Launcher icon sizes for Android 7, which has no adaptive icons. */
const LEGACY_LAUNCHER_SIZES = {
  mdpi: 48,
  hdpi: 72,
  xhdpi: 96,
  xxhdpi: 144,
  xxxhdpi: 192,
} as const;

function write(relativeToRes: string, contents: string) {
  const file = path.join(RES_DIR, relativeToRes);
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, contents);
}

async function main() {
  write(
    "drawable/ic_launcher_foreground.xml",
    staticIconVector(LAUNCHER_FOREGROUND)
  );
  write("drawable/splash_icon_animated.xml", animatedSplashIcon());

  await renderPngs([
    ...Object.entries(LEGACY_LAUNCHER_SIZES).flatMap(([density, size]) => [
      {
        file: path.join(RES_DIR, `mipmap-${density}/ic_launcher.png`),
        svg: iconSvg({
          width: size,
          iconWidth: size * 0.7,
          tile: { shape: "rounded", color: "#ffffff" },
        }),
        width: size,
      },
      {
        file: path.join(RES_DIR, `mipmap-${density}/ic_launcher_round.png`),
        svg: iconSvg({
          width: size,
          iconWidth: size * 0.64,
          tile: { shape: "circle", color: "#ffffff" },
        }),
        width: size,
      },
    ]),
    {
      // Google Play rounds the corners itself and wants a full square.
      file: path.join(MOBILE_DIR, "assets/play-store-icon.png"),
      svg: iconSvg({
        width: 512,
        iconWidth: 512 * 0.6,
        tile: { shape: "square", color: "#ffffff" },
      }),
      width: 512,
    },
  ]);
}

await main();
